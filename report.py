"""Render a DarkSight report card.   python report.py evidence/booking_blr.json"""
import json, sys, html, pathlib, time
from detect import audit

ICON = {"fail": ("✕", "#FF5A36"), "warn": ("!", "#FACC15"), "pass": ("✓", "#22C55E")}


def render(path):
    ev = json.loads(pathlib.Path(path).read_text())
    grade, findings = audit(ev)
    rows = "".join(
        f'<div class="row"><span class="dot" style="background:{ICON[v][1]}">{ICON[v][0]}</span>'
        f'<b>{html.escape(n)}</b><span class="muted">{html.escape(d)}</span></div>'
        for v, n, d in findings)
    steps = "".join(
        f'<li><b>Step {s.get("step", i + 1)}</b> · {html.escape(str(s.get("page", "")))}: '
        f'₹{s["price_shown_inr"]:,.0f}<span class="muted"> {html.escape(s.get("note") or "")}</span></li>'
        for i, s in enumerate(ev.get("steps", [])) if s.get("price_shown_inr"))
    title = ev.get("hotel_name") or ev.get("platform")
    page = f"""<!doctype html><meta charset="utf-8"><title>DarkSight · {html.escape(title)}</title>
<style>body{{background:#0E1015;color:#F5F5F4;font:16px system-ui;max-width:760px;margin:40px auto;padding:0 16px}}
.card{{background:#1A1D26;border-radius:14px;padding:24px;margin:16px 0}}.muted{{color:#A1A1AA;font-size:14px}}
.row{{display:grid;grid-template-columns:32px 180px 1fr;gap:12px;align-items:center;padding:10px 0}}
.dot{{width:24px;height:24px;border-radius:50%;display:grid;place-items:center;color:#0E1015;font-weight:700}}
.grade{{font-size:64px;font-weight:800;color:#FF5A36;float:right;line-height:1}}h1{{margin:0}}li{{margin:6px 0}}
@media(max-width:600px){{.row{{grid-template-columns:32px 1fr}}.row .muted{{grid-column:2}}}}</style>
<p class="muted">DARKSIGHT REPORT CARD · {html.escape(ev.get("category", ""))} · run {html.escape(str(ev.get("run_id", ""))[:8])}</p>
<div class="card"><span class="grade">{grade}</span><h1>{html.escape(title)}</h1>
<p class="muted">{html.escape(ev.get("platform", ""))} · captured {html.escape(ev.get("captured_at", ""))}</p>{rows}</div>
<div class="card"><b>Price trail recorded by the TinyFish agent</b><ul>{steps}</ul></div>"""
    dest = pathlib.Path(f"report_{pathlib.Path(path).stem}.html")
    dest.write_text(page)
    print("wrote", dest)


if __name__ == "__main__":
    render(sys.argv[1])


def complaint(ev):
    """Printable complaint draft (browser 'Save as PDF') built from one run's evidence."""
    from detect import report
    r = report(ev)
    e = lambda x: html.escape(str(x if x is not None else ""))
    inr = lambda n: "₹{:,.2f}".format(n).replace(".00", "") if isinstance(n, (int, float)) else "not recorded"
    fees = "".join(f"<tr><td>{e(f['label'])}</td><td class=n>{inr(f['amount_inr'])}</td><td>{e(f['explanation'])}</td></tr>"
                   for f in r["fees"])
    issues = [f for f in r["findings"] if f["verdict"] != "pass"]
    items = "".join(f"<li><b>{e(f['name'])}</b>: {e(f['detail'])}<br><span class=m>{e(f['why'])}</span></li>" for f in issues) \
        or "<li>No dark-pattern signals were found in this run.</li>"
    steps = "".join(f"<li>{e(s.get('page'))}{' · ' + inr(s.get('price_shown_inr')) if s.get('price_shown_inr') is not None else ''}"
                    f"<br><span class=m>{e(s.get('note'))}</span></li>" for s in ev.get("steps", []))
    what = ev.get("hotel_name") or ev.get("item") or "the selected item"
    return f"""<!doctype html><meta charset="utf-8"><title>Complaint draft · {e(ev.get('platform'))}</title>
<meta name="color-scheme" content="light"><style>html{{background:#fff}}body{{background:#fff;font:14px/1.55 Georgia,serif;color:#111;max-width:760px;margin:32px auto;padding:0 24px}}
h1{{font-size:20px;margin:0 0 4px}}h2{{font-size:15px;margin:22px 0 6px}}table{{width:100%;border-collapse:collapse}}
td{{border-top:1px solid #ccc;padding:6px 8px 6px 0;vertical-align:top}}td.n{{white-space:nowrap;text-align:right;font-weight:bold}}
.m{{color:#555;font-size:12.5px}}.box{{border:1px solid #999;padding:10px 12px;background:#f6f6f6}}.fill{{background:#fff3b0}}
.bar{{position:sticky;top:0;background:#0E1015;color:#fff;padding:10px;margin:-32px -24px 20px;text-align:center;font:14px system-ui}}
.bar button{{background:#FF5A36;border:0;color:#0E1015;font-weight:700;padding:8px 14px;border-radius:6px;cursor:pointer}}
@media print{{.bar{{display:none}}.fill{{background:none}}}}</style>
<div class=bar>Complaint draft generated by DarkSight. Fill the highlighted fields, then <button onclick="print()">Save as PDF</button></div>
<p><b>To:</b> National Consumer Helpline (NCH), Department of Consumer Affairs, Government of India<br>
<span class=m>File online at consumerhelpline.gov.in or call 1915. Forwarded for consideration by the Central Consumer Protection Authority (CCPA).</span></p>
<p><b>From:</b> <span class=fill>[Your full name]</span>, <span class=fill>[Your city]</span>, <span class=fill>[Phone / email]</span><br>
<b>Date:</b> {time.strftime('%d %B %Y')}</p>
<h1>Complaint: dark patterns on {e(ev.get('platform'))}</h1>
<p class=m>Under the Guidelines for Prevention and Regulation of Dark Patterns, 2023 (Consumer Protection Act, 2019)</p>
<h2>1. What happened</h2>
<p>On {e(str(ev.get('captured_at', ''))[:10])}, a checkout on <b>{e(ev.get('platform'))}</b> for <b>{e(what)}</b> was recorded
step by step, stopping before payment. The price shown when the item was selected was <b>{inr(r['listed_price'])}</b>.
The amount payable at checkout was <b>{inr(r['total'])}</b>{f" (<b>{r['markup_pct']:+d}%</b>)" if r['markup_pct'] is not None else ""}.</p>
<h2>2. Charges added after the item was selected</h2>
<table><tr><td>Price shown when selected</td><td class=n>{inr(r['listed_price'])}</td><td></td></tr>{fees}
<tr><td><b>Total payable</b></td><td class=n>{inr(r['total'])}</td><td></td></tr></table>
<h2>3. Practices I am reporting</h2><ul>{items}</ul>
<h2>4. Evidence</h2>
<p class=box>Recorded by an automated browser agent (TinyFish). Run ID {e(ev.get('run_id'))}, captured {e(ev.get('captured_at'))},
{e(ev.get('agent_steps'))} steps. Evidence file: evidence/{e(ev.get('scenario'))}.json</p><ol>{steps}</ol>
<h2>5. What I request</h2>
<p>That the platform be asked to show the full payable amount, including all mandatory fees, at the point where the price is
first displayed, and that the practices above be examined under the 2023 Guidelines.</p>
<p>Signature: <span class=fill>[Your name]</span></p>
<p class=m>Draft generated by DarkSight from recorded evidence. Review and verify every detail before filing. This is not legal advice.</p>"""
